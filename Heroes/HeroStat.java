package Heroes;

/**
 * Enumeration representing all hero statistics that can be modified
 * by potions or other game mechanics.
 * HP – Health points
 * MP – Mana points (legacy name; equivalent to MANA)
 * STRENGTH – Physical attack power
 * DEXTERITY – Spell accuracy and spell damage scaling
 * MANA – Total mana capacity
 * AGILITY – Dodge chance scaling
 */
public enum HeroStat {
    HP, MP, STRENGTH, DEXTERITY, MANA, AGILITY
}
