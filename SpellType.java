/**
 * Enumeration of all spell elemental types in the game.
 * ICE       – Reduces monster damage after hit
 * FIRE      – Reduces monster defense after hit
 * LIGHTNING – Reduces monster dodge chance after hit
 * Each type determines the secondary debuff effect applied
 * when a spell successfully hits a monster.
 */
public enum SpellType {
    ICE, FIRE, LIGHTNING
}
